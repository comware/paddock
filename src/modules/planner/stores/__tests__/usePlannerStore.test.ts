describe('Edge Cases', () => {
  it('handles event with all optional fields undefined', () => {
    const event = createMockEvent({
      speciesId: undefined,
      trayId: undefined,
      batchId: undefined,
      stationId: undefined,
      notes: undefined,
      completedDate: undefined,
    });

    expect(event.title).toBeDefined();
    expect(event.eventType).toBeDefined();
    expect(event.scheduledDate).toBeDefined();
    expect(event.status).toBeDefined();
    expect(event.siteId).toBeDefined();
  });

  it('handles dates at exactly midnight', () => {
    const midnight = new Date();
    midnight.setHours(0, 0, 0, 0);

    const event = createMockEvent({ scheduledDate: midnight });
    expect(event.scheduledDate.getTime()).toBe(midnight.getTime());
  });

  it('handles dates at end of day', () => {
    const endOfDay = new Date();
    endOfDay.setHours(23, 59, 59, 999);

    const event = createMockEvent({ scheduledDate: endOfDay });
    expect(event.scheduledDate).toBeDefined();
  });

  it('handles empty events array', () => {
    const events: PlannerEvent[] = [];

    const counts: Record<PlannerEventStatus, number> = {
      scheduled: 0,
      pending: 0,
      completed: 0,
      cancelled: 0,
      skipped: 0,
    };

    for (const event of events) {
      counts[event.status]++;
    }

    expect(counts.scheduled).toBe(0);
    expect(counts.completed).toBe(0);
  });

  it('handles very long titles', () => {
    const longTitle = 'A'.repeat(100);
    const event = createMockEvent({ title: longTitle });
    expect(event.title).toHaveLength(100);
  });

  it('handles special characters in notes', () => {
    const notes = 'Check for pests! 🐛 <script>alert("xss")</script>';
    const event = createMockEvent({ notes });
    expect(event.notes).toBe(notes);
  });

  it('handles events far in the future', () => {
    const farFuture = new Date();
    farFuture.setFullYear(farFuture.getFullYear() + 10);

    const event = createMockEvent({ scheduledDate: farFuture });

    const today = new Date();
    const scheduled = new Date(event.scheduledDate);
    const todayMidnight = new Date(today.getFullYear(), today.getMonth(), today.getDate());
    const scheduledMidnight = new Date(scheduled.getFullYear(), scheduled.getMonth(), scheduled.getDate());
    const daysUntil = Math.floor((scheduledMidnight.getTime() - todayMidnight.getTime()) / (1000 * 60 * 60 * 24));

    expect(daysUntil).toBeGreaterThan(3600); // > 10 years
  });

  it('handles events far in the past', () => {
    const farPast = new Date();
    farPast.setFullYear(farPast.getFullYear() - 10);

    const event = createMockEvent({
      scheduledDate: farPast,
      status: 'scheduled',
    });

    const today = new Date();
    const scheduled = new Date(event.scheduledDate);
    const todayMidnight = new Date(today.getFullYear(), today.getMonth(), today.getDate());
    const scheduledMidnight = new Date(scheduled.getFullYear(), scheduled.getMonth(), scheduled.getDate());
    const daysUntil = Math.floor((scheduledMidnight.getTime() - todayMidnight.getTime()) / (1000 * 60 * 60 * 24));

    expect(daysUntil).toBeLessThan(-3600); // > 10 years ago
  });
});
