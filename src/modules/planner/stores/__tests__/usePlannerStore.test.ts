describe('Computed Fields', () => {
  describe('daysUntil calculation', () => {
    it('returns positive days for future events', () => {
      const event = createMockEvent({ scheduledDate: daysFromNow(5) });
      const today = new Date();
      const scheduled = new Date(event.scheduledDate);
      const todayMidnight = new Date(today.getFullYear(), today.getMonth(), today.getDate());
      const scheduledMidnight = new Date(scheduled.getFullYear(), scheduled.getMonth(), scheduled.getDate());
      const daysUntil = Math.floor((scheduledMidnight.getTime() - todayMidnight.getTime()) / (1000 * 60 * 60 * 24));

      expect(daysUntil).toBe(5);
    });

    it('returns 0 for today', () => {
      const event = createMockEvent({ scheduledDate: new Date() });
      const today = new Date();
      const scheduled = new Date(event.scheduledDate);
      const todayMidnight = new Date(today.getFullYear(), today.getMonth(), today.getDate());
      const scheduledMidnight = new Date(scheduled.getFullYear(), scheduled.getMonth(), scheduled.getDate());
      const daysUntil = Math.floor((scheduledMidnight.getTime() - todayMidnight.getTime()) / (1000 * 60 * 60 * 24));

      expect(daysUntil).toBe(0);
    });

    it('returns negative days for past events', () => {
      const event = createMockEvent({ scheduledDate: daysAgo(3) });
      const today = new Date();
      const scheduled = new Date(event.scheduledDate);
      const todayMidnight = new Date(today.getFullYear(), today.getMonth(), today.getDate());
      const scheduledMidnight = new Date(scheduled.getFullYear(), scheduled.getMonth(), scheduled.getDate());
      const daysUntil = Math.floor((scheduledMidnight.getTime() - todayMidnight.getTime()) / (1000 * 60 * 60 * 24));

      expect(daysUntil).toBe(-3);
    });
  });

  describe('isOverdue detection', () => {
    function checkIsOverdue(event: PlannerEvent): boolean {
      if (event.status === 'completed' || event.status === 'cancelled' || event.status === 'skipped') {
        return false;
      }
      const today = new Date();
      const scheduled = new Date(event.scheduledDate);
      const todayMidnight = new Date(today.getFullYear(), today.getMonth(), today.getDate());
      const scheduledMidnight = new Date(scheduled.getFullYear(), scheduled.getMonth(), scheduled.getDate());
      return scheduledMidnight.getTime() < todayMidnight.getTime();
    }

    it('returns true for past scheduled events', () => {
      const event = createMockEvent({
        scheduledDate: daysAgo(2),
        status: 'scheduled',
      });
      expect(checkIsOverdue(event)).toBe(true);
    });

    it('returns false for future events', () => {
      const event = createMockEvent({
        scheduledDate: daysFromNow(2),
        status: 'scheduled',
      });
      expect(checkIsOverdue(event)).toBe(false);
    });

    it('returns false for completed events even if past date', () => {
      const event = createMockEvent({
        scheduledDate: daysAgo(5),
        status: 'completed',
      });
      expect(checkIsOverdue(event)).toBe(false);
    });

    it('returns false for cancelled events', () => {
      const event = createMockEvent({
        scheduledDate: daysAgo(5),
        status: 'cancelled',
      });
      expect(checkIsOverdue(event)).toBe(false);
    });

    it('returns false for skipped events', () => {
      const event = createMockEvent({
        scheduledDate: daysAgo(5),
        status: 'skipped',
      });
      expect(checkIsOverdue(event)).toBe(false);
    });

    it('returns false for today (not overdue until tomorrow)', () => {
      const event = createMockEvent({
        scheduledDate: new Date(),
        status: 'scheduled',
      });
      expect(checkIsOverdue(event)).toBe(false);
    });
  });

  describe('isPending detection', () => {
    function checkIsPending(event: PlannerEvent): boolean {
      if (event.status === 'completed' || event.status === 'cancelled' || event.status === 'skipped') {
        return false;
      }
      const today = new Date();
      const scheduled = new Date(event.scheduledDate);
      return (
        today.getFullYear() === scheduled.getFullYear() &&
        today.getMonth() === scheduled.getMonth() &&
        today.getDate() === scheduled.getDate()
      );
    }

    it('returns true for events scheduled today', () => {
      const event = createMockEvent({
        scheduledDate: new Date(),
        status: 'scheduled',
      });
      expect(checkIsPending(event)).toBe(true);
    });

    it('returns false for future events', () => {
      const event = createMockEvent({
        scheduledDate: daysFromNow(1),
        status: 'scheduled',
      });
      expect(checkIsPending(event)).toBe(false);
    });

    it('returns false for past events', () => {
      const event = createMockEvent({
        scheduledDate: daysAgo(1),
        status: 'scheduled',
      });
      expect(checkIsPending(event)).toBe(false);
    });

    it('returns false for completed events on today', () => {
      const event = createMockEvent({
        scheduledDate: new Date(),
        status: 'completed',
      });
      expect(checkIsPending(event)).toBe(false);
    });
  });
});

