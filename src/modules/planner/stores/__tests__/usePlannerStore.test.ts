describe('Date Range Queries', () => {
  function isWithinRange(date: Date, start: Date, end: Date): boolean {
    const d = new Date(date).setHours(0, 0, 0, 0);
    const s = new Date(start).setHours(0, 0, 0, 0);
    const e = new Date(end).setHours(23, 59, 59, 999);
    return d >= s && d <= e;
  }

  it('includes events on start date', () => {
    const start = daysFromNow(0);
    const end = daysFromNow(7);
    const event = createMockEvent({ scheduledDate: start });

    expect(isWithinRange(event.scheduledDate, start, end)).toBe(true);
  });

  it('includes events on end date', () => {
    const start = daysFromNow(0);
    const end = daysFromNow(7);
    const event = createMockEvent({ scheduledDate: end });

    expect(isWithinRange(event.scheduledDate, start, end)).toBe(true);
  });

  it('includes events within range', () => {
    const start = daysFromNow(0);
    const end = daysFromNow(7);
    const event = createMockEvent({ scheduledDate: daysFromNow(3) });

    expect(isWithinRange(event.scheduledDate, start, end)).toBe(true);
  });

  it('excludes events before range', () => {
    const start = daysFromNow(5);
    const end = daysFromNow(10);
    const event = createMockEvent({ scheduledDate: daysFromNow(2) });

    expect(isWithinRange(event.scheduledDate, start, end)).toBe(false);
  });

  it('excludes events after range', () => {
    const start = daysFromNow(0);
    const end = daysFromNow(5);
    const event = createMockEvent({ scheduledDate: daysFromNow(10) });

    expect(isWithinRange(event.scheduledDate, start, end)).toBe(false);
  });
});

