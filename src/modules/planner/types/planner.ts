// ============================================
// TYPE GUARDS
// ============================================

/**
 * Check if an object is a PlannerEvent.
 */
export function isPlannerEvent(obj: unknown): obj is PlannerEvent {
  if (!obj || typeof obj !== 'object') return false;
  const event = obj as Partial<PlannerEvent>;
  return (
    typeof event.title === 'string' &&
    typeof event.eventType === 'string' &&
    event.scheduledDate instanceof Date &&
    typeof event.status === 'string' &&
    typeof event.siteId === 'string'
  );
}

/**
 * Check if an event has a linked entity.
 */
export function hasLinkedEntity(event: PlannerEvent): boolean {
  return !!(event.trayId || event.batchId);
}

/**
 * Get the linked entity type if any.
 */
export function getLinkedEntityType(event: PlannerEvent): 'tray' | 'batch' | null {
  if (event.trayId) return 'tray';
  if (event.batchId) return 'batch';
  return null;
}

/**
 * Get the linked entity ID if any.
 */
export function getLinkedEntityId(event: PlannerEvent): string | null {
  return event.trayId || event.batchId || null;
}
