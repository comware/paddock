export type { PlannerEventType };

// ============================================
// EVENT STATUS
// ============================================

/**
 * Status lifecycle for planner events.
 * Events progress through these states as they are worked.
 */
export type PlannerEventStatus =
  | 'scheduled'  // Future event, not yet due
  | 'pending'    // Due today or overdue, needs action
  | 'completed'  // Successfully completed
  | 'cancelled'  // No longer needed, removed from schedule
  | 'skipped';   // Deliberately skipped, not applicable

/**
 * All valid statuses as an array for iteration.
 */
export const ALL_EVENT_STATUSES: PlannerEventStatus[] = [
  'scheduled',
  'pending',
  'completed',
  'cancelled',
  'skipped',
];

/**
 * Statuses that represent active/actionable events.
 */
export const ACTIVE_STATUSES: PlannerEventStatus[] = ['scheduled', 'pending'];

/**
 * Statuses that represent terminal states.
 */
export const TERMINAL_STATUSES: PlannerEventStatus[] = ['completed', 'cancelled', 'skipped'];

/**
 * Check if a status is active (requires action).
 */
export function isActiveStatus(status: PlannerEventStatus): boolean {
  return ACTIVE_STATUSES.includes(status);
}

/**
 * Check if a status is terminal (no further action).
 */
export function isTerminalStatus(status: PlannerEventStatus): boolean {
  return TERMINAL_STATUSES.includes(status);
}

// ============================================
// CORE ENTITIES
// ============================================

/**
 * Core planner event entity.
 * Represents a single scheduled activity in the calendar.
 *
 * Key invariants:
 * - At most one of trayId or batchId can be set (mutual exclusivity)
 * - siteId is always required for location context
 * - isAutoGenerated events are derived from trays/batches
 */
export interface PlannerEvent {
  id?: string;

  // Core Fields
  title: string;
  eventType: PlannerEventType;
  scheduledDate: Date;
  completedDate?: Date;
  status: PlannerEventStatus;

  // Optional Linking (at most one)
  speciesId?: string;          // Link to variety/species config
  trayId?: string;             // Link to GrowTray
  batchId?: string;            // Link to PropBatch

  // Location Context
  siteId: string;              // Required: FK to GrowSite
  stationId?: string;          // Optional: FK to PropStation

  // Additional Data
  notes?: string;

  // Auto-generation tracking
  isAutoGenerated: boolean;
  sourceType?: 'tray' | 'batch';
  sourceId?: string;           // ID of generating entity

  // Timestamps
  createdAt: Date;
  updatedAt: Date;
}

/**
 * Enriched event with computed fields for UI display.
 * These fields are calculated at runtime, not persisted.
 */
export interface PlannerEventWithComputed extends PlannerEvent {
  daysUntil: number;           // Days until scheduledDate (negative if past)
  isOverdue: boolean;          // Past scheduledDate and not completed
  isPending: boolean;          // Due today
  displayColor: string;        // Based on eventType and status
  linkedEntityName?: string;   // Tray/batch identifier for display
}

